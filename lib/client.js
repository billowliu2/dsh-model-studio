		/**
		 * Capability reference index, built once per session.
		 *
		 * The installed catalog already IS a models.dev-grade database (the probe
		 * measured 40 providers / ~920 ids answered locally in ~8 ms), so this
		 * project needs no bundled snapshot at all — and therefore cannot suffer the
		 * two-snapshots-drifting-apart problem the reference implementation has.
		 */
		const referenceIndex = { index: null, state: "idle", stats: null };
		let referencePromise = null;
		/**
		 * Build the reference index by asking the catalog about every provider it
		 * ships. All of those calls are answered locally, with no network.
		 *
		 * @param llm - the `remote.llm` face.
		 * @param directory - `llm/listConfigurableProviders` output.
		 * @returns a promise for the index (or `null` when there is nothing to index).
		 */
		function ensureReference(llm, directory) {
			if (referenceIndex.index !== null) return Promise.resolve(referenceIndex.index);
			if (referencePromise !== null) return referencePromise;
			const catalog = (directory ?? []).filter((entry) => entry?.declared !== true && typeof entry?.provider === "string");
			if (llm === undefined || llm === null || catalog.length === 0) return Promise.resolve(null);
			referenceIndex.state = "building";
			referencePromise = (async () => {
				const sources = [];
				// Chunked: a ~40-entry fan-out stays a few round trips wide instead of
				// flooding the remote channel.
				for (let at = 0; at < catalog.length; at += 8) {
					const answers = await Promise.all(catalog.slice(at, at + 8).map(async (entry) => {
						try {
							const value = unwrapResult(await llm.discoverModels("llm-pi-ai", { provider: entry.provider }));
							return { route: entry.provider, models: Array.isArray(value) ? value : [] };
						} catch {
							// One provider failing must not cost us the rest of the index.
							return { route: entry.provider, models: [] };
						}
					}));
					for (const answer of answers) sources.push(answer);
				}
				const index = buildReferenceIndex(sources);
				referenceIndex.index = index;
				referenceIndex.stats = { providers: index.providers, ids: index.ids };
				referenceIndex.state = index.ids > 0 ? "ready" : "empty";
				referencePromise = null;
				return index;
			})();
			return referencePromise;
		}
