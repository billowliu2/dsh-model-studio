		/**
		 * The reasoning efforts one route/model actually accepts.
		 *
		 * Read from the host's catalog rather than assumed: pi-ai *throws*
		 * `UNSUPPORTED_REASONING_EFFORT` for a level the model does not offer, so a
		 * global default chosen from an invented list would fail every request on
		 * that model. An unknown model therefore offers no levels at all.
		 */
		function effortChoices(catalog, selection) {
			const entry = catalogEntry(catalog, selection);
			const efforts = Array.isArray(entry?.reasoning?.efforts) ? entry.reasoning.efforts : [];
			return {
				known: entry !== undefined,
				efforts: efforts.map((effort) => ({
					id: String(effort.id),
					name: typeof effort.name === "string" && effort.name !== "" ? effort.name : String(effort.id),
				})),
				defaultId: typeof entry?.reasoning?.defaultEffort === "string" ? entry.reasoning.defaultEffort : "",
			};
		}
		/**
		 * Provider presets: routes the installed catalog serves with a credential alone.
		 *
		 * The directory states where each provider's config lives, so only routes in
		 * this plugin's own namespace are offered. A built-in route such as
		 * `deepseek-official` lives in `llm-deepseek` and is not ours to create; and a
		 * route that is already configured is left out rather than silently replaced.
		 */
		function presetOptions(directory, configured) {
			const taken = new Set(configured ?? []);
			return (directory ?? [])
				.filter((entry) => entry?.settingsNs === "llm-pi-ai" && entry?.declared !== true)
				.filter((entry) => typeof entry.provider === "string" && entry.provider !== "" && !taken.has(entry.provider))
				.map((entry) => ({
					id: entry.provider,
					label: typeof entry.displayName === "string" && entry.displayName !== "" ? entry.displayName : entry.provider,
				}))
				.sort((left, right) => left.id.localeCompare(right.id));
		}
		/** Unwrap a remote call's answer, turning `{ok:false}` into a thrown error. */
		function unwrapResult(result) {
			if (result !== null && typeof result === "object") {
				if (result.ok === true) return "value" in result ? result.value : result;
				if (result.ok === false) {
					const detail = result.error ?? {};
					const failure = new Error(typeof detail.message === "string" ? detail.message : "请求被宿主拒绝");
					if (typeof detail.code === "string") failure.code = detail.code;
					throw failure;
				}
			}
			return result;
		}
		/** Human-readable text for anything a write path can throw. */
		function errorText(error) {
			if (error === null || error === undefined) return "未知错误";
			const message = typeof error.message === "string" && error.message.length > 0 ? error.message : String(error);
			const code = typeof error.code === "string" ? error.code : "";
			if (code === "SETTINGS_CONFLICT") return "配置已被其他写入改动（SETTINGS_CONFLICT）：" + message;
			return code.length > 0 ? code + ": " + message : message;
		}
		/**
		 * Store an API key and, on a route that had no reference, record the derived
		 * one. The key itself goes only to the credentials seam — `settings.yaml`
		 * gets the reference name and nothing else.
		 */
		async function saveApiKey(input) {
			if (!isPrintableAsciiKey(input.key)) {
				throw new Error("密钥必须是非空的可打印 ASCII 字符（与 HTTP 头值同字符集）");
			}
			if (input.credentials === undefined || input.credentials === null) {
				throw copyError("dataUnavailable", undefined, undefined, "credentials service unavailable");
			}
			const ref = input.currentRef !== "" ? input.currentRef : deriveKeyRef(input.route);
			unwrapResult(await input.credentials.set(ref, input.key));
			if (input.currentRef === "") {
				unwrapResult(await input.scope.mutate(
					[{ op: "set", path: ["providers", input.route, "apiKeyEnv"], value: ref }],
					input.revision,
				));
				return { ref, wroteRef: true };
			}
			return { ref, wroteRef: false };
		}
		/** Describe one credential reference without ever reading its value. */
		async function describeKey(credentials, ref) {
			if (ref === "" || credentials === undefined || credentials === null) return { configured: false, source: "", writable: false, known: false };
			try {
				const answer = unwrapResult(await credentials.describe(ref));
				return {
					configured: answer?.configured === true,
					source: typeof answer?.source === "string" ? answer.source : "",
					writable: answer?.writable !== false,
					known: true,
				};
			} catch {
				return { configured: false, source: "", writable: false, known: false };
			}
		}
