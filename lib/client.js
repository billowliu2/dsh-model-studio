		/** Whether a string is a resolvable absolute HTTP(S) endpoint. */
		function isEndpoint(value) {
			if (!/^https?:\/\//i.test(value)) return false;
			try {
				return new URL(value).hostname.length > 0;
			} catch {
				return false;
			}
		}
		/**
		 * The path ops that realize an edited basic profile.
		 *
		 * A cleared field is *unset*, never written empty: absent means "inherit the
		 * installed catalog's value", which is the only way to give a catalog route
		 * its default endpoint or protocol back.
		 *
		 * @param {string} route - provider route key.
		 * @param {object} draft - the edited values.
		 * @returns {ReadonlyArray<object>} path ops, in a stable order.
		 */
		function basicOps(route, draft) {
			const displayName = draft.displayName.trim();
			const api = draft.api.trim();
			const baseURL = draft.baseURL.trim().replace(/\/+$/, "");
			if (api !== "" && PROTOCOLS.indexOf(api) === -1) {
				throw new Error("API 格式只能是 " + PROTOCOLS.join(" / "));
			}
			if (baseURL !== "" && !isEndpoint(baseURL)) {
				throw new Error("请求地址必须是可解析的 http(s) URL");
			}
			const field = (fieldName) => ["providers", route, fieldName];
			return [
				displayName === "" ? { op: "unset", path: field("displayName") } : { op: "set", path: field("displayName"), value: displayName },
				api === "" ? { op: "unset", path: field("api") } : { op: "set", path: field("api"), value: api },
				baseURL === "" ? { op: "unset", path: field("baseURL") } : { op: "set", path: field("baseURL"), value: baseURL },
			];
		}
		/** The path ops that create a hand-declared route (one pi-ai does not ship). */
		function createOps(draft) {
			const route = draft.route.trim();
			if (!/^[a-z0-9][a-z0-9-]*$/.test(route)) {
				throw new Error("Provider ID 只能用小写字母、数字和连字符，且以字母或数字开头");
			}
			// A provider the installed catalog already ships needs neither protocol nor
			// endpoint to work — the catalog knows both — but both stay *editable* as
			// optional overrides (a proxy or gateway in front of a known provider), and
			// no model list is needed either, because an undeclared list serves every
			// model the catalog has for that route.
			if (typeof draft.preset === "string" && draft.preset !== "") {
				const profile = { apiKeyEnv: deriveKeyRef(route) };
				if (draft.displayName.trim() !== "") profile.displayName = draft.displayName.trim();
				// The snapshot pre-fills protocol and endpoint so the form documents what
				// the catalog will use. A value the user did not touch *is* the catalog's
				// own value, so it stays out of the config: naming a protocol rebuilds a
				// catalog route over that protocol instead of reusing the catalog
				// provider, and a stale snapshot must never break a request.
				const api = typeof draft.api === "string" ? draft.api : "";
				if (api !== "" && api !== (draft.presetApi ?? "")) {
					if (PROTOCOLS.indexOf(api) === -1) throw new Error("API 格式必须是 pi-ai 支持的三种协议之一");
					profile.api = api;
				}
				const endpoint = String(draft.baseURL ?? "").trim().replace(/\/+$/, "");
				if (endpoint !== "" && endpoint !== String(draft.presetBaseUrl ?? "").replace(/\/+$/, "")) {
					if (!isEndpoint(endpoint)) throw new Error("请求地址必须是可解析的 http(s) URL");
					profile.baseURL = endpoint;
				}
				return [{ op: "set", path: ["providers", route], value: profile }];
			}
			if (PROTOCOLS.indexOf(draft.api) === -1) {
				throw new Error("自定义供应商必须明确 API 格式");
			}
			if (!isEndpoint(draft.baseURL.trim())) {
				throw new Error("请求地址必须是可解析的 http(s) URL");
			}
			if (draft.modelId.trim() === "") {
				throw new Error("自定义供应商至少需要一个模型 id");
			}
			const profile = {
				api: draft.api,
				baseURL: draft.baseURL.trim().replace(/\/+$/, ""),
				models: [{ id: draft.modelId.trim() }],
			};
			if (draft.displayName.trim() !== "") profile.displayName = draft.displayName.trim();
			return [{ op: "set", path: ["providers", route], value: profile }];
		}
