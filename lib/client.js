		/**
		 * Resolve a possibly-dotted service from a context.
		 *
		 * `remote.llm` and `remote.credentials` are separate *services* the api
		 * gateway mounts as each package's client half arrives; they are not
		 * properties of the `remote` service instance, so walking that object finds
		 * nothing. The context is the resolver.
		 */
		function serviceOf(ctx, name) {
			if (ctx === undefined || ctx === null) return undefined;
			if (typeof ctx.get === "function") {
				const direct = ctx.get(name);
				if (direct !== undefined) return direct;
			}
			let node = ctx;
			for (const part of String(name).split(".")) {
				if (node === undefined || node === null) return undefined;
				node = node[part];
			}
			return node;
		}
		/** Build an Error that carries a locale key, so the UI can phrase it in the user's language. */
		function copyError(copyKey, copyVarName, copyVarValue, fallback) {
			const error = new Error(fallback);
			error.copyKey = copyKey;
			error.copyVarName = copyVarName;
			error.copyVarValue = copyVarValue;
			return error;
		}
		/** Path ops that store (or clear) a route's custom request headers. */
		function headersOps(route, rows) {
			const headers = {};
			for (const row of rows) {
				const headerName = String(row.key ?? "").trim();
				const value = String(row.value ?? "");
				if (headerName === "" && value === "") continue;
				if (headerName === "") throw copyError("headerEmptyName", undefined, undefined, "header name required");
				if (!HEADER_NAME_RE.test(headerName)) throw copyError("headerInvalidName", "name", headerName, "invalid header name: " + headerName);
				if (!/^[\x20-\x7E]*$/.test(value)) throw copyError("headerInvalidValue", undefined, undefined, "header value must be printable ASCII");
				headers[headerName] = value;
			}
			const path = ["providers", route, "headers"];
			return [Object.keys(headers).length === 0 ? { op: "unset", path } : { op: "set", path, value: headers }];
		}
		/** Wrap a `llm/discoverModels` answer the way the stock page does. */
		function discoveryOutcome(result) {
			try {
				const value = unwrapResult(result);
				return { kind: "ok", models: Array.isArray(value) ? value : [] };
			} catch (error) {
				return { kind: "refused", message: errorText(error) };
			}
		}
		/** Merge fetched candidates into an explicit model list; ids already present keep their draft. */
		function mergeDiscovered(existing, picked, candidates, enableThinking) {
			const byId = new Map(existing.map((draft) => [draft.id, draft]));
			for (const candidate of candidates) {
				if (picked.indexOf(candidate.id) === -1 || byId.has(candidate.id)) continue;
				byId.set(candidate.id, draftFromCandidate(candidate, enableThinking));
			}
			return Array.from(byId.values());
		}
		/** One fetched candidate as an editable draft. */
		function draftFromCandidate(candidate, enableThinking) {
			// Reference data, when the catalog published it, wins over the blanket
			// "declare thinking" checkbox: a guessed level set is worse than none.
			const efforts = candidate.reasoningEfforts;
			const levels = efforts !== null && typeof efforts === "object" ? Object.keys(efforts) : [];
			const modalities = Array.isArray(candidate.input) ? candidate.input : [];
			return {
				id: candidate.id,
				name: typeof candidate.name === "string" ? candidate.name : "",
				contextWindow: typeof candidate.contextWindow === "number" ? String(candidate.contextWindow) : "",
				maxTokens: typeof candidate.maxTokens === "number" ? String(candidate.maxTokens) : "",
				input: modalities.indexOf("image") !== -1 ? "text+image" : "inherit",
				reasoning: levels.length > 0 ? "custom" : enableThinking === true ? "custom" : "inherit",
				levels: levels.length > 0 ? levels : enableThinking === true ? THINKING_LEVELS.slice() : [],
			};
		}

		// #region reference index
		/**
		 * Normalize a model id for reference matching.
		 *
		 * Wire ids and catalog ids disagree on spelling: marketing suffixes
		 * (`glm-5.2-highspeed`), router tags (`kimi-k3:free`), context tags
		 * (`-256k`), and dated snapshots (`-20250929`, `-0731`). Only those are
		 * stripped — punctuation is left alone, because the dot form is what the
		 * catalog usually uses (`glm-5.2`); the `p`-encoded spelling is registered as
		 * an extra alias instead of replacing it.
		 *
		 * Normalization only ever *adds* a candidate, and the stage that matched
		 * travels with the hit so the UI never claims more certainty than it has — an
		 * unranked suffix match once resolved a model to a reseller entry and
		 * silently dropped its reasoning flag in the project this design borrows from.
		 */
		function normalizeModelId(id) {
			return String(id ?? "").trim().toLowerCase()
				.replace(/-(highspeed|latest|preview|beta|stable|exp|free|turbo)$/g, "")
				.replace(/-(1m|\d+k)$/g, "")
				.replace(/-\d{8}$/g, "")
				.replace(/-\d{4}-\d{2}-\d{2}$/g, "")
				.replace(/-\d{4}$/g, "")
				.replace(/(:free|-free)$/g, "");
		}
		/** The same id with `.`/`:` encoded as `p`, the spelling some catalogs use. */
		function dotVariant(id) {
			return String(id ?? "").replace(/[.:]/g, "p");
		}
		/** Every key one catalog id is registered under: exact, bare, normalized, p-encoded. */
		function referenceAliases(id) {
			const lower = String(id ?? "").trim().toLowerCase();
			if (lower === "") return [];
			const bare = lower.indexOf("/") === -1 ? lower : lower.slice(lower.lastIndexOf("/") + 1);
			const keys = [lower, bare];
			for (const form of [lower, bare]) {
				keys.push(normalizeModelId(form), dotVariant(normalizeModelId(form)));
			}
			return keys.filter((key) => key !== "").filter((key, at) => keys.indexOf(key) === at);
		}
		/**
		 * Merge two catalog entries for the same model, filling gaps only.
		 *
		 * Providers disagree about which fields they publish — a Bedrock entry has a
		 * context window but no modalities — so first-wins would throw away data a
		 * later provider supplies. `0` context and an empty modality list mean "not
		 * applicable", never "zero": copying them would store a broken value.
		 */
		function mergeReferenceEntry(left, right) {
			if (left === undefined || left === null) return right ?? {};
			const merged = Object.assign({}, left);
			for (const [key, value] of Object.entries(right ?? {})) {
				const current = merged[key];
				const missing = current === undefined || current === null || (Array.isArray(current) && current.length === 0);
				const meaningful = value !== null && value !== undefined && !(Array.isArray(value) && value.length === 0);
				if (missing && meaningful && !(key === "contextWindow" && value <= 0)) merged[key] = value;
			}
			return merged;
		}
		/**
		 * Build the reference index from what the installed catalog declares.
		 *
		 * @param sources - `[{route, models}]` per catalog provider.
		 * @returns `{byKey, ids, providers}` with one key per id plus its aliases.
		 */
		function buildReferenceIndex(sources) {
			const byKey = new Map();
			const ids = new Set();
			let providers = 0;
			for (const source of sources ?? []) {
				if (source === null || source === undefined || !Array.isArray(source.models)) continue;
				if (source.models.length > 0) providers += 1;
				for (const model of source.models) {
					if (model === null || typeof model !== "object" || typeof model.id !== "string") continue;
					ids.add(model.id.toLowerCase());
					for (const key of referenceAliases(model.id)) {
						byKey.set(key, mergeReferenceEntry(byKey.get(key), model));
					}
				}
			}
			return { byKey, ids: ids.size, providers };
		}
		/**
		 * Find reference metadata for a wire id.
		 *
		 * The ladder is a plain map hit at each step because the index registered
		 * every alias up front — no linear scan per lookup, which is the other
		 * lesson from the reference implementation.
		 */
		function lookupReference(index, id) {
			if (index === null || index === undefined || index.byKey === undefined) return undefined;
			const lower = String(id ?? "").trim().toLowerCase();
			if (lower === "") return undefined;
			const bare = lower.indexOf("/") === -1 ? lower : lower.slice(lower.lastIndexOf("/") + 1);
			const ladder = [
				{ stage: "exact", key: lower },
				{ stage: "bare", key: bare },
				{ stage: "normalized", key: normalizeModelId(lower) },
				{ stage: "normalized-bare", key: normalizeModelId(bare) },
				{ stage: "normalized-p", key: dotVariant(normalizeModelId(lower)) },
				{ stage: "normalized-bare-p", key: dotVariant(normalizeModelId(bare)) },
			];
			for (const step of ladder) {
				const hit = index.byKey.get(step.key);
				if (hit !== undefined) return { model: hit, stage: step.stage, trusted: step.stage === "exact" || step.stage === "bare" };
			}
			return undefined;
		}
		/**
		 * Fill a discovered model's empty fields from reference data.
		 *
		 * This is what makes a custom endpoint usable: `/models` answers with bare
		 * ids, while the installed catalog knows the context window and output limit.
		 * Nothing is invented — a field the catalog does not publish stays absent so
		 * the config keeps inheriting instead of storing a guess.
		 *
		 * Measured on dsh 0.1.5-rc.2: the catalog's discovery answer carries
		 * `id`/`name`/`contextWindow`/`maxTokens` for all 891 ids, but never
		 * `input`/`reasoningEfforts` (0/891), so modalities and thinking levels stay
		 * a manual decision. The branches are kept because the shape is the host's to
		 * extend, and copying them would then be correct with no code change.
		 */
		function applyReference(model, hit) {
			if (hit === undefined) return model;
			const source = hit.model ?? {};
			const out = Object.assign({}, model);
			if (typeof out.name !== "string" && typeof source.name === "string" && source.name !== "") out.name = source.name;
			if (typeof out.contextWindow !== "number" && typeof source.contextWindow === "number" && source.contextWindow > 0) {
				out.contextWindow = source.contextWindow;
			}
			if (typeof out.maxTokens !== "number" && typeof source.maxTokens === "number" && source.maxTokens > 0) {
				out.maxTokens = source.maxTokens;
			}
			if (!Array.isArray(out.input) && Array.isArray(source.input) && source.input.length > 0) out.input = source.input.slice();
			// Only a same-id match reuses the level map: a normalized match may be a
			// different minor version, whose reasoning wire spelling is a guess.
			if (hit.trusted && out.reasoningEfforts === undefined && source.reasoningEfforts !== undefined && source.reasoningEfforts !== null) {
				out.reasoningEfforts = source.reasoningEfforts;
			}
			out.reference = { from: source.id, stage: hit.stage, trusted: hit.trusted };
			return out;
		}
		/** Enrich a discovery result; `explained` counts the ids the catalog knew. */
		function withReference(models, index) {
			if (index === null || index === undefined || index.byKey === undefined) return { models, explained: 0 };
			let explained = 0;
			const enriched = models.map((model) => {
				const hit = lookupReference(index, model.id);
				if (hit !== undefined) explained += 1;
				return applyReference(model, hit);
			});
			return { models: enriched, explained, known: explained === models.length };
		}
		/**
		 * Fill one capability draft's empty fields from reference data.
		 *
		 * Never overwrites: a value the user typed, or one the config already
		 * declares, is not the editor's to replace.
		 */
		function fillDraftFromReference(draft, hit) {
			if (hit === undefined) return { draft, filled: 0 };
			const source = hit.model ?? {};
			const next = Object.assign({}, draft);
			let filled = 0;
			if (next.name.trim() === "" && typeof source.name === "string" && source.name !== "") {
				next.name = source.name;
				filled += 1;
			}
			if (next.contextWindow.trim() === "" && typeof source.contextWindow === "number" && source.contextWindow > 0) {
				next.contextWindow = String(source.contextWindow);
				filled += 1;
			}
			if (next.maxTokens.trim() === "" && typeof source.maxTokens === "number" && source.maxTokens > 0) {
				next.maxTokens = String(source.maxTokens);
				filled += 1;
			}
			if (next.input === "inherit" && Array.isArray(source.input) && source.input.indexOf("image") !== -1) {
				next.input = "text+image";
				filled += 1;
			}
			if (hit.trusted && next.reasoning === "inherit" && source.reasoningEfforts !== undefined && source.reasoningEfforts !== null) {
				const levels = Object.keys(source.reasoningEfforts);
				if (levels.length > 0) {
					next.reasoning = "custom";
					next.levels = levels;
					filled += 1;
				}
			}
			return { draft: next, filled, stage: hit.stage, from: typeof source.id === "string" ? source.id : "" };
		}
