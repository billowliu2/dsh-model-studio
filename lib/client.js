		/**
		 * The model-mapping section.
		 *
		 * Two surfaces, one editor: a route with an explicit `models` list edits
		 * that list, while a catalog route edits `modelOverrides` entries so the
		 * other thirty-odd catalog models keep serving untouched. The discovery
		 * list drives both.
		 */
		function ModelSection(props) {
			const t = props.t;
			const candidates = props.candidates;
			const existing = props.existingIds ?? [];
			const query = props.candidateQuery.trim().toLowerCase();
			const visible = candidates === null ? [] : candidates.filter((candidate) => {
				if (query === "") return true;
				const id = String(candidate.id).toLowerCase();
				const name = typeof candidate.name === "string" ? candidate.name.toLowerCase() : "";
				return id.indexOf(query) !== -1 || name.indexOf(query) !== -1;
			});
			const info = props.info;
			const children = [
				h("div", { className: cx.sectionTitle, key: "title" },
					t("modelsEdit") + " · " + props.rows.length,
					h("span", { className: cx.tag }, props.explicit ? t("tagDeclared") : t("tagCatalog")),
					props.dirty === true ? h("span", { className: cx.tag }, t("unsaved")) : null,
				),
				h("div", { className: cx.hint, key: "surface" }, props.explicit ? t("modelsExplicit") : t("modelsNote")),
				h("div", { className: cx.actions, key: "toolbar" },
					h("button", { className: cx.button, type: "button", disabled: props.busy || props.catalogBusy, onClick: props.onFetch },
						props.catalogBusy ? t("discovering") : t("discover")),
					h("button", {
						className: cx.button,
						type: "button",
						disabled: props.busy || props.rows.length === 0,
						title: t("refFillHint") + (props.reference === null || props.reference === undefined
							? ""
							: " · " + t("refCoverage").replace("{n}", String(props.reference.ids))),
						onClick: props.onFillReference,
					}, t("refFill")),
					candidates !== null
						? textInput(props.candidateQuery, props.onQuery, { placeholder: t("searchModels"), style: { maxWidth: "200px" } })
						: null,
				),
			];

			// What the last read produced — or why there is nothing to read.
			if (info !== null && info !== undefined && info.error !== undefined) {
				children.push(h("div", { className: cx.warn, key: "info" },
					info.error,
					info.stale === true ? h("span", { className: cx.hint }, " " + t("refStale")) : null));
			} else if (info !== null && info !== undefined) {
				children.push(h("div", { className: info.count === 0 ? cx.warn : cx.hint, key: "info" }, info.count === 0
					? t("discoverEmpty")
					: t("discoverSummary")
						.replace("{n}", String(info.count))
						.replace("{ms}", String(info.ms))
						.replace("{source}", info.source === "endpoint" ? t("discoverSourceEndpoint") : t("discoverSourceCatalog"))
						+ (info.explained > 0
							? " · " + t("refExplained").replace("{n}", String(info.explained)).replace("{m}", String(info.count))
							: "")));
			} else if (props.catalogBusy) {
				children.push(h("div", { className: cx.hint, key: "info" }, t("discoverLoading")));
			} else if (props.interrogable === false && props.explicit === false) {
				children.push(h("div", { className: cx.warn, key: "info" }, t("discoverNeedEndpoint")));
			}

			if (candidates !== null) {
				children.push(h("div", { className: cx.actions, key: "cand-head" },
					h("span", { className: cx.hint }, t("discovered").replace("{n}", String(candidates.length))),
					h("button", { className: cx.button, type: "button", onClick: () => props.onSelectAll(visible.map((candidate) => candidate.id)) }, t("selectAll")),
					h("button", { className: cx.button, type: "button", onClick: props.onClearAll }, t("clearAll")),
					h("button", { className: cx.button, type: "button", onClick: () => props.onInvert(visible.map((candidate) => candidate.id)) }, t("invertAll")),
				));
				children.push(h("label", { className: cx.candidate, key: "thinking" },
					h("input", { type: "checkbox", checked: props.enableThinking, onChange: (event) => props.onToggleThinking(event.target.checked) }),
					t("enableThinkingOnAdd"),
				));
				children.push(h("div", { className: cx.candidates, key: "cand-list" },
					visible.map((candidate) => {
						const known = existing.indexOf(candidate.id) !== -1;
						const ref = candidate.reference;
						return h("label", { className: cx.candidate, key: candidate.id },
							h("input", {
								type: "checkbox",
								checked: props.picked.indexOf(candidate.id) !== -1,
								disabled: known && props.explicit,
								onChange: () => props.onTogglePick(candidate.id),
							}),
							h("code", null, candidate.id),
							typeof candidate.contextWindow === "number" ? h("span", { className: cx.hint }, String(candidate.contextWindow)) : null,
							// Say where a capability came from: the endpoint published nothing,
							// the installed catalog knew the model, and the match stage is the
							// honest confidence label for that.
							ref === undefined ? null : h("span", {
								className: cx.tag + " " + cx.tagDeclared,
								title: t("refMatch").replace("{from}", String(ref.from)).replace("{stage}", String(ref.stage)),
							}, t("refTag")),
							known ? h("span", { className: cx.tag }, t("discoverExisting")) : null,
						);
					}),
				));
				children.push(h("div", { className: cx.actions, key: "cand-add" },
					h("button", {
						className: cx.button + " " + cx.buttonPrimary,
						type: "button",
						disabled: props.busy || props.picked.length === 0,
						onClick: props.onAddSelected,
					}, t("addSelected").replace("{n}", String(props.picked.length))),
					props.sync !== null && props.sync !== undefined ? h("button", {
						className: cx.button,
						type: "button",
						disabled: props.busy,
						title: t("syncHint"),
						onClick: props.onSync,
					}, t("syncModels")
						.replace("{add}", String(props.sync.missing.length))
						.replace("{remove}", String(props.sync.gone.length))) : null,
				));
			}
			if (props.rows.length === 0) {
				children.push(h("div", { className: cx.hint, key: "empty" }, props.catalogBusy ? t("discoverLoading") : t("providersEmpty")));
			}
			children.push(h("div", { key: "rows", style: { display: "flex", flexDirection: "column", gap: "8px" } },
				props.rows.map((row) => h(ModelCard, {
					key: row.id,
					t,
					draft: row.draft,
					source: row.source,
					onChange: (next) => props.onRowChange(row.id, next),
					onRemove: () => props.onRowRemove(row.id),
				})),
			));
			if (props.rows.length > 0) children.push(h("div", { className: cx.hint, key: "inherit" }, t("inheritHint")));
			children.push(h("div", { className: cx.actions, key: "save" },
				h("button", { className: cx.button + " " + cx.buttonPrimary, type: "button", disabled: props.busy, onClick: props.onSave },
					props.busy ? t("saving") : t("saveModels")),
			));
			return h("div", { className: cx.section }, children);
		}

